"""
Library of published parameter sets (starting values and references for fits).

The sets come from the literature database of MyDEP 1.0.1 (Cottet et al., Biophys J 116 (2019) 12-18,
doi:10.1016/j.bpj.2018.11.021), MIT licence; the notice and licence text travel with the data file
(src/models/data/mydep_library.json, generated by tests/tools/mydep_to_library.py). Every set also cites
the publication its values come from. Ellipsoidal particles are not included yet.
"""
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
import json

from src.models.catalog import MODELS

LIBRARY_FILE = Path(__file__).parent / 'data' / 'mydep_library.json'

## Data classes ##


@dataclass(frozen=True)
class Reference:
    """
    The publication a parameter set comes from.
    """
    authors: str
    year: int
    title: str
    journal: str
    doi: str

    def short(self) -> str:
        first = self.authors.split(',')[0].strip()
        return f'{first} et al. {self.year}' if '&' in self.authors or self.authors.count(',') > 2 else \
            f'{first} {self.year}'


@dataclass(frozen=True)
class ParameterSet:
    """
    One published particle / cell.
    """
    name: str
    model: str                        # catalog model key
    values: dict                      # display units
    reference: Reference
    remark: str
    source: str                       # e.g. 'MyDEP 1.0.1 database'


## Loading ##


@lru_cache(maxsize=1)
def _load() -> dict:
    return json.loads(LIBRARY_FILE.read_text(encoding='utf-8'))


def parameter_sets(model: str | None = None) -> list[ParameterSet]:
    """
    Published parameter sets, optionally of one model.

    Args:
        model (str | None): Catalog model key (None = all).

    Returns:
        list[ParameterSet]: Sets in library order.
    """
    out = []
    for e in _load()['entries']:
        # Sets of models this program does not offer (e.g. the C_mem / G_mem single-shell form) are skipped
        if e['model'] not in MODELS or (model is not None and e['model'] != model):
            continue
        out.append(ParameterSet(e['name'], e['model'], dict(e['values']), Reference(**e['reference']),
                                e.get('remark', ''), e.get('source', '')))
    return out


def notice() -> str:
    """
    Attribution and licence of the library (shown in the GUI and the user guide).

    Returns:
        str: Notice text.
    """
    data = _load()
    return f"{data['notice']}\n\n{data['licence']} licence: {data['licence_text']}"


def check_library() -> list[str]:
    """
    Problems in the library: unknown models or parameters, missing ones.

    Returns:
        list[str]: Messages (empty when everything matches the catalog).
    """
    problems = []
    for s in parameter_sets():
        model = MODELS.get(s.model)
        if model is None:
            problems.append(f'{s.name}: unknown model {s.model}')
            continue
        keys = {p.key for p in model.parameters}
        if set(s.values) != keys:
            problems.append(f'{s.name}: parameters {sorted(set(s.values) ^ keys)} do not match {s.model}')
    return problems
